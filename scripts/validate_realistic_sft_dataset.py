from __future__ import annotations

import argparse
import json
import pathlib

try:
    from scripts.build_realistic_sft_dataset import SOURCE_KIND, build_outputs, load_family_spec
except ModuleNotFoundError:
    from build_realistic_sft_dataset import SOURCE_KIND, build_outputs, load_family_spec


def _load_jsonl(path: pathlib.Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def validate_repository(root: pathlib.Path) -> dict:
    root = pathlib.Path(root)
    base = root / "experiments" / "needle-realistic-sft"
    family_path = base / "source" / "families.json"
    semantic_path = base / "source" / "semantic-cases.jsonl"

    semantic_rows = _load_jsonl(semantic_path)
    bad_source = [row.get("case_id") for row in semantic_rows if row.get("source_kind") != SOURCE_KIND]
    if bad_source:
        raise ValueError(f"baseline source kind violation: {bad_source[0]}")

    spec = load_family_spec(family_path)
    outputs = build_outputs(spec)
    if len(outputs["train"]) != 360 or len(outputs["heldout"]) != 96:
        raise ValueError("dataset geometry mismatch")

    for relative, expected in outputs["files"].items():
        path = base / relative
        if not path.exists():
            raise ValueError(f"generated file missing: {relative}")
        observed = path.read_bytes()
        if observed != expected:
            raise ValueError(f"generated byte mismatch: {relative}")

    return {
        "status": "VERIFIED",
        "train_rows": len(outputs["train"]),
        "heldout_rows": len(outputs["heldout"]),
        "source_kind": SOURCE_KIND,
        "verified_files": sorted(outputs["files"]),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Validate committed Needle Stage B deterministic dataset artifacts.")
    parser.add_argument("--root", type=pathlib.Path, default=pathlib.Path(__file__).resolve().parents[1])
    args = parser.parse_args(argv)
    result = validate_repository(args.root)
    print(json.dumps(result, ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
